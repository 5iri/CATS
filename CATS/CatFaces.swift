    static func levelFor(xp: Int) -> (name: String, cat: String, xpRequired: Int) {
        var current = levels[0]
        for level in levels {
            if xp >= level.xpRequired {
                current = level
            } else {
                break
            }
        }
        return current
    }

    static func nextLevelFor(xp: Int) -> (name: String, cat: String, xpRequired: Int)? {
        for level in levels {
            if xp < level.xpRequired {
                return level
            }
        }
        return nil
    }
