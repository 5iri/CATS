    static func forMood(energy: Double) -> String {
        switch energy {
        case 80...100: return "(=^･ω･^=)"
        case 60..<80:  return "(ΦωΦ)"
        case 40..<60:  return "ฅ(´-ω-`)ฅ"
        case 20..<40:  return "(=;ω;=)"
        default:       return "(ↀДↀ)"
        }
    }

